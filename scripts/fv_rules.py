"""Generate the project-local rule set.

Rules are copied from the skill's ``rules/`` directory with project values
substituted, so every design sees the same policy.  A manifest records each
file hash and one aggregate ``rules_sha256``.  The aggregate is embedded in the
bundle, harness and results, which makes "the rules changed" visible without
relying on timestamps.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from fv_common import (
    FvError,
    SKILL_ROOT,
    SKILL_VERSION,
    canonical_json,
    project_root,
    read_json,
    rel_to,
    sha256_file,
    sha256_text,
    write_json,
    write_text,
)

RULES_SCHEMA_VERSION = "1.0"
TEMPLATE_DIR = SKILL_ROOT / "rules"


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _templates() -> list[Path]:
    if not TEMPLATE_DIR.is_dir():
        raise FvError(f"rule templates not found: {TEMPLATE_DIR}")
    return sorted(TEMPLATE_DIR.glob("*.md"))


def _substitute(text: str, values: dict[str, str]) -> str:
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def _render(template: Path, values: dict[str, str]) -> str:
    body = _substitute(template.read_text(encoding="utf-8"), values)
    header = (f"<!-- generated by formal-sva {SKILL_VERSION}; "
              "regenerate with `fv.py rules --design ...`; do not edit -->\n")
    if body.startswith("# "):
        first, _, rest = body.partition("\n")
        body = first + "\n\n" + header + rest.lstrip("\n")
    else:
        body = header + body
    return body


def generate(manifest: dict[str, Any], force: bool = False,
             quiet: bool = False) -> dict[str, Any]:
    root = project_root(manifest)
    out_dir = Path(manifest["_paths"]["rules"])
    manifest_path = out_dir / "manifest.json"
    templates = _templates()
    if not templates:
        raise FvError(f"no rule templates in {TEMPLATE_DIR}")

    spec = manifest.get("spec") or {}
    spec_path = root / str(spec.get("markdown") or "spec/spec.md")
    tools_path = Path(manifest["_paths"]["tools"])
    values = {
        "SKILL_VERSION": SKILL_VERSION,
        "DESIGN": str(manifest.get("name") or manifest.get("top") or "design"),
        "TOP": str(manifest.get("top") or ""),
        "SPEC": rel_to(root, spec_path),
        "TOOLS": rel_to(root, tools_path),
        "GENERATED_AT": _now(),
    }

    existing = read_json(manifest_path) if manifest_path.is_file() else None
    wanted = {p.name: sha256_text(_render(p, values)) for p in templates}
    if (not force and isinstance(existing, dict)
            and (existing.get("files") or {}) == wanted
            and existing.get("skill_version") == SKILL_VERSION):
        return existing

    out_dir.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {}
    for template in templates:
        write_text(out_dir / template.name, _render(template, values))
        files[template.name] = sha256_file(out_dir / template.name)

    rules_sha = sha256_text(canonical_json(files))
    doc = {
        "schema_version": RULES_SCHEMA_VERSION,
        "generated_at": _now(),
        "generated_by": "formal-sva/fv_rules.py",
        "skill_version": SKILL_VERSION,
        "design": values["DESIGN"],
        "top": values["TOP"],
        "spec": values["SPEC"],
        "spec_sha256": sha256_file(spec_path) if spec_path.is_file() else "",
        "tools": values["TOOLS"],
        "tools_sha256": sha256_file(tools_path) if tools_path.is_file() else "",
        "files": files,
        "rules_sha256": rules_sha,
    }
    write_json(manifest_path, doc)
    if not quiet:
        print(f"rules: {rel_to(root, out_dir)}")
        print(f"  {len(files)} file(s), rules_sha256={rules_sha[:16]}...")
    return doc


def _source_values(manifest: dict[str, Any]) -> dict[str, str]:
    root = project_root(manifest)
    spec = manifest.get("spec") or {}
    spec_path = root / str(spec.get("markdown") or "spec/spec.md")
    tools_path = Path(manifest["_paths"]["tools"])
    return {
        "DESIGN": str(manifest.get("name") or manifest.get("top") or "design"),
        "TOP": str(manifest.get("top") or ""),
        "SPEC": rel_to(root, spec_path),
        "SPEC_SHA256": sha256_file(spec_path) if spec_path.is_file() else "",
        "TOOLS": rel_to(root, tools_path),
        "TOOLS_SHA256": sha256_file(tools_path) if tools_path.is_file() else "",
    }


def ensure(manifest: dict[str, Any], quiet: bool = True) -> dict[str, Any]:
    path = Path(manifest["_paths"]["rules"]) / "manifest.json"
    if not path.is_file():
        return generate(manifest, quiet=quiet)
    try:
        existing = read_json(path)
    except FvError:
        return generate(manifest, quiet=quiet)

    # Detect hand edits before any regeneration.
    disk_errors = check(manifest)
    source = _source_values(manifest)
    values = {
        "SKILL_VERSION": SKILL_VERSION,
        "DESIGN": source["DESIGN"],
        "TOP": source["TOP"],
        "SPEC": source["SPEC"],
        "TOOLS": source["TOOLS"],
        "GENERATED_AT": str(existing.get("generated_at") or ""),
    }
    wanted = {p.name: sha256_text(_render(p, values)) for p in _templates()}
    stale_manifest = any(existing.get(key) != value for key, value in (
        ("skill_version", SKILL_VERSION),
        ("design", source["DESIGN"]),
        ("top", source["TOP"]),
        ("spec", source["SPEC"]),
        ("spec_sha256", source["SPEC_SHA256"]),
        ("tools", source["TOOLS"]),
        ("tools_sha256", source["TOOLS_SHA256"]),
    ))
    needs_regen = stale_manifest or (existing.get("files") or {}) != wanted
    if disk_errors:
        if needs_regen:
            # Templates/source changed, but on-disk rules were also hand-edited.
            # Refuse silent overwrite; user must regenerate explicitly.
            raise FvError(
                "generated rule files were modified and are also stale; "
                "regenerate explicitly with `fv.py rules --design ... --force`:\n"
                + "\n".join(f"  {e}" for e in disk_errors))
        raise FvError(
            "generated rule files were modified; regenerate with "
            "`fv.py rules --design ...`:\n"
            + "\n".join(f"  {e}" for e in disk_errors))
    if needs_regen:
        return generate(manifest, force=True, quiet=quiet)
    return existing


def ensure_consistent(manifest: dict[str, Any], quiet: bool = True) -> dict[str, Any]:
    """Generate or refresh the rule files, then refuse a hand-edited rule set."""
    doc = ensure(manifest, quiet=quiet)
    errors = check(manifest)
    if errors:
        raise FvError(
            "generated rule files are inconsistent; regenerate them with "
            "`fv.py rules --design ...`:\n" + "\n".join(f"  {e}" for e in errors)
        )
    return doc


def rules_hash(manifest: dict[str, Any]) -> str:
    path = Path(manifest["_paths"]["rules"]) / "manifest.json"
    if not path.is_file():
        return ""
    try:
        return str(read_json(path).get("rules_sha256") or "")
    except FvError:
        return ""


def check(manifest: dict[str, Any]) -> list[str]:
    path = Path(manifest["_paths"]["rules"]) / "manifest.json"
    if not path.is_file():
        return [f"rule manifest missing: {path}"]
    try:
        doc = read_json(path)
    except FvError as exc:
        return [str(exc)]
    errors: list[str] = []
    for name, digest in (doc.get("files") or {}).items():
        file_path = Path(manifest["_paths"]["rules"]) / name
        if not file_path.is_file():
            errors.append(f"rule file missing: {name}")
        elif sha256_file(file_path) != digest:
            errors.append(f"rule file modified: {name} (regenerate with fv.py rules)")
    if not errors and sha256_text(canonical_json(doc.get("files") or {})) != doc.get("rules_sha256"):
        errors.append("rule manifest rules_sha256 does not match its file table")
    return errors
